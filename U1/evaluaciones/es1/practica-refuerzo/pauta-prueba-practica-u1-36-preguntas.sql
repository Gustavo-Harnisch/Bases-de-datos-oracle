FROM OEHR_EMPLOYEES;

-- =============================================================================
-- TEMA 5: FUNCIONES DE GRUPO, GROUP BY Y HAVING
-- =============================================================================

-- Pregunta 25
SELECT ROUND(AVG(SALARY), 0) AS "PROMEDIO",
       MIN(SALARY) AS "MINIMO",
       MAX(SALARY) AS "MAXIMO"
FROM OEHR_EMPLOYEES;

-- Pregunta 26
SELECT COUNT(DISTINCT DEPARTMENT_ID) AS "DEPARTAMENTOS_CON_EMPLEADOS"
FROM OEHR_EMPLOYEES;

-- Pregunta 27
SELECT JOB_ID AS "CARGO",
       COUNT(EMPLOYEE_ID) AS "CANTIDAD_EMPLEADOS",
       ROUND(AVG(SALARY), 0) AS "PROMEDIO_SUELDOS",
       MAX(SALARY) - MIN(SALARY) AS "DIFERENCIA_SUELDOS"
FROM OEHR_EMPLOYEES
GROUP BY JOB_ID
HAVING MAX(SALARY) - MIN(SALARY) <> 0;

-- Pregunta 28
SELECT DEPARTMENT_ID AS "COD_DEPARTAMENTO",
       JOB_ID AS "CARGO",
       TO_CHAR(SUM(SALARY), 'FM$999G999G990D00',
               'NLS_NUMERIC_CHARACTERS=''.,''') AS "TOTAL_SUELDOS"
FROM OEHR_EMPLOYEES
WHERE DEPARTMENT_ID BETWEEN 50 AND 100
GROUP BY DEPARTMENT_ID, JOB_ID
ORDER BY DEPARTMENT_ID, JOB_ID;

-- Pregunta 29
SELECT DEPARTMENT_ID AS "COD_DEPARTAMENTO",
       ROUND(AVG(SALARY), 0) AS "PROMEDIO_SUELDOS"
FROM OEHR_EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING AVG(SALARY) > 8000
ORDER BY "PROMEDIO_SUELDOS" DESC;

-- Pregunta 30
SELECT JOB_ID AS "CARGO",
       COUNT(EMPLOYEE_ID) AS "TOTAL_EMPLEADOS",
       COUNT(COMMISSION_PCT) AS "EMPLEADOS_CON_COMISION"
FROM OEHR_EMPLOYEES
GROUP BY JOB_ID
HAVING COUNT(EMPLOYEE_ID) >= 2;

-- =============================================================================
-- TEMA 6: JOIN, CLAVES FORANEAS, AUTORRELACIONES Y SUBCONSULTAS
-- =============================================================================

-- Pregunta 31
SELECT E.EMPLOYEE_ID AS "COD_EMPLEADO",
       E.FIRST_NAME || ' ' || E.LAST_NAME AS "NOMBRE_EMPLEADO",
       J.JOB_TITLE AS "CARGO",
       D.DEPARTMENT_NAME AS "DEPARTAMENTO"
FROM OEHR_EMPLOYEES E
JOIN OEHR_JOBS J
  ON E.JOB_ID = J.JOB_ID
JOIN OEHR_DEPARTMENTS D
  ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;

-- Pregunta 32
SELECT E.EMPLOYEE_ID AS "COD_EMPLEADO",
       E.LAST_NAME AS "APELLIDO",
       L.CITY AS "CIUDAD",
       C.COUNTRY_NAME AS "PAIS",
       R.REGION_NAME AS "REGION"
FROM OEHR_EMPLOYEES E
JOIN OEHR_DEPARTMENTS D
  ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN OEHR_LOCATIONS L
  ON D.LOCATION_ID = L.LOCATION_ID
JOIN OEHR_COUNTRIES C
  ON L.COUNTRY_ID = C.COUNTRY_ID
JOIN OEHR_REGIONS R
  ON C.REGION_ID = R.REGION_ID;

-- Pregunta 33
SELECT E.EMPLOYEE_ID AS "COD_EMPLEADO",
       E.FIRST_NAME || ' ' || E.LAST_NAME AS "EMPLEADO",
       M.FIRST_NAME || ' ' || M.LAST_NAME AS "JEFE_DIRECTO"
FROM OEHR_EMPLOYEES E
LEFT JOIN OEHR_EMPLOYEES M
  ON E.MANAGER_ID = M.EMPLOYEE_ID;

-- Pregunta 34
SELECT D.DEPARTMENT_ID AS "COD_DEPARTAMENTO",
       D.DEPARTMENT_NAME AS "DEPARTAMENTO",
       M.FIRST_NAME || ' ' || M.LAST_NAME AS "JEFE_DEPARTAMENTO"
FROM OEHR_DEPARTMENTS D
LEFT JOIN OEHR_EMPLOYEES M
  ON D.MANAGER_ID = M.EMPLOYEE_ID;

-- Pregunta 35
SELECT E.EMPLOYEE_ID AS "COD_EMPLEADO",
       E.LAST_NAME AS "APELLIDO",
       H.START_DATE AS "FECHA_INICIO",
       H.END_DATE AS "FECHA_TERMINO",
       J.JOB_TITLE AS "CARGO_HISTORICO",
       D.DEPARTMENT_NAME AS "DEPARTAMENTO_HISTORICO"
FROM OEHR_JOB_HISTORY H
JOIN OEHR_EMPLOYEES E
  ON H.EMPLOYEE_ID = E.EMPLOYEE_ID
JOIN OEHR_JOBS J
  ON H.JOB_ID = J.JOB_ID
LEFT JOIN OEHR_DEPARTMENTS D
  ON H.DEPARTMENT_ID = D.DEPARTMENT_ID;

-- Pregunta 36
SELECT E.EMPLOYEE_ID AS "COD_EMPLEADO",
       E.FIRST_NAME || ' ' || E.LAST_NAME AS "NOMBRE_EMPLEADO",
       D.DEPARTMENT_NAME AS "DEPARTAMENTO",
       J.JOB_TITLE AS "CARGO",
       E.COMMISSION_PCT AS "COMISION"
FROM OEHR_EMPLOYEES E
JOIN OEHR_DEPARTMENTS D
  ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN OEHR_JOBS J
  ON E.JOB_ID = J.JOB_ID
WHERE E.DEPARTMENT_ID IN (
          SELECT DEPARTMENT_ID
          FROM OEHR_EMPLOYEES
          WHERE UPPER(LAST_NAME) IN ('WHALEN', 'KING')
      )
  AND E.COMMISSION_PCT IS NOT NULL
  AND E.SALARY NOT BETWEEN 5000 AND 10000
ORDER BY D.DEPARTMENT_NAME, E.LAST_NAME;

