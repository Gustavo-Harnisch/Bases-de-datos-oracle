-- Pregunta 22
SELECT EMPLOYEE_ID AS "COD_EMPLEADO",
       LAST_NAME AS "APELLIDO",
       NVL2(COMMISSION_PCT, 'CON COMISION', 'SIN COMISION') AS "ESTADO_COMISION"
