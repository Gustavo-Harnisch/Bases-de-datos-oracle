-- =============================================================================
-- TEMA 2: RESTRICCION, OPERADORES, PATRONES, NULOS Y ORDENAMIENTO
-- =============================================================================

-- Pregunta 7
SELECT EMPLOYEE_ID AS "COD_EMPLEADO",
       LAST_NAME AS "APELLIDO",
       SALARY AS "SUELDO",
       DEPARTMENT_ID AS "COD_DEPARTAMENTO"
FROM OEHR_EMPLOYEES
WHERE SALARY BETWEEN 5000 AND 10000
  AND DEPARTMENT_ID IN (50, 80)
ORDER BY SALARY DESC, LAST_NAME ASC;

-- Pregunta 8
