       ROUND(SALARY / 7, 2) AS "CUOTA_REDONDEADA",
       MOD(TRUNC(SALARY), 7) AS "RESTO_DIVISION"
FROM OEHR_EMPLOYEES;

-- Pregunta 18
SELECT EMAIL AS "EMAIL_ORIGINAL",
       SUBSTR(EMAIL, 1, LENGTH(EMAIL) - 2) ||
       SUBSTR(EMAIL, LENGTH(EMAIL), 1) || '@sql.cl' AS "EMAIL_PROPUESTO"
