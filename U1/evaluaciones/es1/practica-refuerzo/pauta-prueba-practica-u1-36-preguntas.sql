       LAST_NAME AS "APELLIDO",
       HIRE_DATE AS "FECHA_CONTRATACION",
       COMMISSION_PCT AS "COMISION"
FROM OEHR_EMPLOYEES
WHERE HIRE_DATE >= DATE '2015-01-01'
  AND COMMISSION_PCT IS NULL
ORDER BY HIRE_DATE ASC;

-- Pregunta 9
