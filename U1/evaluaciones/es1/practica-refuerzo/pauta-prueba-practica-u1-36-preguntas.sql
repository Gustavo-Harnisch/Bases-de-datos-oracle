-- Pregunta 15
SELECT LAST_NAME AS "APELLIDO",
       LENGTH(LAST_NAME) AS "LARGO_APELLIDO",
       SUBSTR(JOB_ID, 1, 3) AS "AREA_CARGO"
FROM OEHR_EMPLOYEES;

-- Pregunta 16
SELECT EMPLOYEE_ID AS "COD_EMPLEADO",
       FIRST_NAME || ' ' || LAST_NAME AS "NOMBRE_COMPLETO",
       HIRE_DATE AS "FECHA_CONTRATACION",
       TRUNC((SYSDATE - HIRE_DATE) / 7) AS "SEMANAS_TRABAJADAS"
