JOIN OEHR_COUNTRIES C ON C.REGION_ID = R.REGION_ID
JOIN OEHR_LOCATIONS L ON L.COUNTRY_ID = C.COUNTRY_ID
JOIN OEHR_DEPARTMENTS D ON D.LOCATION_ID = L.LOCATION_ID
JOIN OEHR_EMPLOYEES E ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN OEHR_JOBS J ON J.JOB_ID = E.JOB_ID
WHERE UPPER(J.JOB_ID) LIKE 'S%'
   OR UPPER(J.JOB_TITLE) LIKE 'S%'
GROUP BY R.REGION_NAME
HAVING COUNT(E.EMPLOYEE_ID) > 1;

