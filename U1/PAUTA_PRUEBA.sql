    E.FIRST_NAME,
    D.DEPARTMENT_NAME,
    J.FIRST_NAME
FROM OEHR_EMPLOYEES E JOIN OEHR_DEPARTMENTS ON(E.DEPARMENT_ID = D.DEPARTMENT_ID)
    JOIN OEHR_EMPLOYEES J ON(E.MANAGER_ID = J.EMPLOYEE_ID);




