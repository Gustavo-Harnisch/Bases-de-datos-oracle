/* ================================================================
   R1 - MODELO RELACIONAL
   ================================================================ */
CREATE TABLE CACB_CLIENTE(
  COD_CLIENTE       NUMBER,
  NOMBRE_CLIENTE    VARCHAR2(50) NOT NULL,
  APELLIDO1_CLIENTE VARCHAR2(50) NOT NULL,
  APELLIDO2_CLIENTE VARCHAR2(50),
  EMAIL_CLIENTE     VARCHAR2(100) NOT NULL,
  CONSTRAINT PK_CACB_CLIENTE PRIMARY KEY (COD_CLIENTE),
  CONSTRAINT UQ_CACB_CLIENTE_EMAIL UNIQUE (EMAIL_CLIENTE)
);

CREATE TABLE CACB_PRODUCTOS(
  COD_PRODUCTO    NUMBER,
  NOMBRE_PRODUCTO VARCHAR2(50) NOT NULL,
  PRECIO_COMPRA   NUMBER(12,2) NOT NULL,
  PRECIO_VENTA    NUMBER(12,2) NOT NULL,
  CANTIDAD        NUMBER DEFAULT 0 NOT NULL,
  STOCK           NUMBER DEFAULT 0 NOT NULL,
  CONSTRAINT PK_CACB_PRODUCTOS PRIMARY KEY (COD_PRODUCTO),
  CONSTRAINT CK_CACB_PRODUCTOS_PRECIOS
    CHECK (PRECIO_COMPRA >= 0 AND PRECIO_VENTA >= 0),
  CONSTRAINT CK_CACB_PRODUCTOS_CANTIDAD CHECK (CANTIDAD >= 0),
  CONSTRAINT CK_CACB_PRODUCTOS_STOCK CHECK (STOCK >= 0)
);

CREATE TABLE CACB_VENTA(
  COD_VENTA    NUMBER,
  FECHA_VENTA  DATE DEFAULT SYSDATE NOT NULL,
  TOTAL_VENTA  NUMBER(12,2) DEFAULT 0 NOT NULL,
  COD_CLIENTE  NUMBER NOT NULL,
  CONSTRAINT PK_CACB_VENTA PRIMARY KEY (COD_VENTA),
  CONSTRAINT FK_CACB_VENTA_CLIENTE
    FOREIGN KEY (COD_CLIENTE) REFERENCES CACB_CLIENTE(COD_CLIENTE)
);

CREATE TABLE CACB_DETALLE_VENTA(
  COD_VENTA    NUMBER,
  COD_PRODUCTO NUMBER,
  CANTIDAD     NUMBER NOT NULL,
  VALOR_TOTAL  NUMBER(12,2) NOT NULL,
  CONSTRAINT PK_CACB_DETALLE_VENTA PRIMARY KEY (COD_VENTA, COD_PRODUCTO),
  CONSTRAINT FK_CACB_DETALLE_VENTA_VENTA
    FOREIGN KEY (COD_VENTA) REFERENCES CACB_VENTA(COD_VENTA),
  CONSTRAINT FK_CACB_DETALLE_VENTA_PRODUCTO
    FOREIGN KEY (COD_PRODUCTO) REFERENCES CACB_PRODUCTOS(COD_PRODUCTO),
  CONSTRAINT CK_CACB_DETALLE_VENTA_CANTIDAD CHECK (CANTIDAD > 0),
  CONSTRAINT CK_CACB_DETALLE_VENTA_TOTAL CHECK (VALOR_TOTAL >= 0)
);

CREATE TABLE CACB_LOG_VENTAS(
  COD_LOG     NUMBER,
  INSTRUCCION VARCHAR2(50),
  DETALLE     VARCHAR2(200),
  FECHAHORA   DATE DEFAULT SYSDATE,
  CONSTRAINT PK_CACB_LOG_VENTAS PRIMARY KEY (COD_LOG)
);

/* ================================================================
