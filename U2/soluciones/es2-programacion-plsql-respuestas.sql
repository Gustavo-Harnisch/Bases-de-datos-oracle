/* ================================================================
   R4 - TRIGGER RECTIFICADOR
   Si cambia COD_VENTA, actualiza sus detalles relacionados.
   ================================================================ */
CREATE OR REPLACE TRIGGER CACB_RECTIFICADOR
BEFORE UPDATE OF COD_VENTA ON CACB_VENTA
FOR EACH ROW
BEGIN
  UPDATE CACB_DETALLE_VENTA
     SET COD_VENTA = :NEW.COD_VENTA
   WHERE COD_VENTA = :OLD.COD_VENTA;
END;
/

/* ================================================================
   R5 - FUNCIÓN DE CORREO DEL CLIENTE
   Formato: NOMBRE.APELLIDO@JUANISMARKET.CL
   En duplicados agrega 1, 2, 3... antes de la arroba.
   ================================================================ */
CREATE OR REPLACE FUNCTION CACB_GENERA_EMAIL(
  NOMBRE_CLIENTE_P    IN CACB_CLIENTE.NOMBRE_CLIENTE%TYPE,
  APELLIDO1_CLIENTE_P IN CACB_CLIENTE.APELLIDO1_CLIENTE%TYPE
) RETURN CACB_CLIENTE.EMAIL_CLIENTE%TYPE
IS
  EMAIL_BASE CACB_CLIENTE.EMAIL_CLIENTE%TYPE;
  EMAIL_FINAL CACB_CLIENTE.EMAIL_CLIENTE%TYPE;
  SUFIJO NUMBER := 0;
  REPETIDOS NUMBER;
BEGIN
  EMAIL_BASE := UPPER(TRIM(NOMBRE_CLIENTE_P)) || '.' ||
                UPPER(TRIM(APELLIDO1_CLIENTE_P)) ||
                '@JUANISMARKET.CL';
  EMAIL_FINAL := EMAIL_BASE;

  LOOP
    SELECT COUNT(*)
      INTO REPETIDOS
      FROM CACB_CLIENTE
     WHERE EMAIL_CLIENTE = EMAIL_FINAL;

    EXIT WHEN REPETIDOS = 0;
    SUFIJO := SUFIJO + 1;
    EMAIL_FINAL := UPPER(TRIM(NOMBRE_CLIENTE_P)) || '.' ||
                   UPPER(TRIM(APELLIDO1_CLIENTE_P)) ||
                   TO_CHAR(SUFIJO) || '@JUANISMARKET.CL';
  END LOOP;

  RETURN EMAIL_FINAL;
EXCEPTION
  WHEN VALUE_ERROR THEN
    RAISE_APPLICATION_ERROR(-20001, 'DATOS INVÁLIDOS PARA EL CORREO');
  WHEN OTHERS THEN
    RAISE_APPLICATION_ERROR(-20002,
      'ERROR AL GENERAR CORREO ' || SQLCODE || ': ' || SQLERRM);
END;
/

/* ================================================================
   R6 - PROCEDIMIENTO INTEGRAL PARA PRODUCTOS (R/U/D)
   ================================================================ */
CREATE OR REPLACE PROCEDURE CACB_PRODUCTOS_RUD(
  OPCION_P         IN VARCHAR2,
  COD_PRODUCTO_P   IN CACB_PRODUCTOS.COD_PRODUCTO%TYPE DEFAULT NULL,
  NOMBRE_PRODUCTO_P IN CACB_PRODUCTOS.NOMBRE_PRODUCTO%TYPE DEFAULT NULL,
  PRECIO_COMPRA_P  IN CACB_PRODUCTOS.PRECIO_COMPRA%TYPE DEFAULT NULL,
  PRECIO_VENTA_P   IN CACB_PRODUCTOS.PRECIO_VENTA%TYPE DEFAULT NULL,
  CANTIDAD_P       IN CACB_PRODUCTOS.CANTIDAD%TYPE DEFAULT NULL,
  STOCK_P          IN CACB_PRODUCTOS.STOCK%TYPE DEFAULT NULL
) IS
  OPCION_LOCAL VARCHAR2(1) := UPPER(TRIM(OPCION_P));
BEGIN
  LOCK TABLE CACB_PRODUCTOS IN ROW EXCLUSIVE MODE;

  IF OPCION_LOCAL = 'R' THEN
    INSERT INTO CACB_PRODUCTOS(
      COD_PRODUCTO, NOMBRE_PRODUCTO, PRECIO_COMPRA,
      PRECIO_VENTA, CANTIDAD, STOCK)
    VALUES (
      COD_PRODUCTO_P, NOMBRE_PRODUCTO_P, PRECIO_COMPRA_P,
      PRECIO_VENTA_P, NVL(CANTIDAD_P, 0), NVL(STOCK_P, 0));

  ELSIF OPCION_LOCAL = 'U' THEN
    UPDATE CACB_PRODUCTOS
       SET PRECIO_COMPRA = PRECIO_COMPRA_P,
           PRECIO_VENTA  = PRECIO_VENTA_P,
           STOCK         = STOCK_P
     WHERE COD_PRODUCTO = COD_PRODUCTO_P;

    IF SQL%ROWCOUNT = 0 THEN
      RAISE_APPLICATION_ERROR(-20011, 'PRODUCTO NO ENCONTRADO');
    END IF;

  ELSIF OPCION_LOCAL = 'D' THEN
    DELETE FROM CACB_PRODUCTOS
     WHERE COD_PRODUCTO = COD_PRODUCTO_P;

    IF SQL%ROWCOUNT = 0 THEN
      RAISE_APPLICATION_ERROR(-20012, 'PRODUCTO NO ENCONTRADO');
    END IF;

  ELSE
    RAISE_APPLICATION_ERROR(-20013, 'OPCIÓN DEBE SER R, U O D');
  END IF;

  INSERT INTO CACB_LOG_VENTAS(INSTRUCCION, DETALLE)
  VALUES ('PRODUCTOS_' || OPCION_LOCAL,
          'COD_PRODUCTO=' || NVL(TO_CHAR(COD_PRODUCTO_P), 'AUTOMÁTICO'));
  COMMIT;
EXCEPTION
  WHEN DUP_VAL_ON_INDEX THEN
    ROLLBACK;
    RAISE_APPLICATION_ERROR(-20014, 'PRODUCTO DUPLICADO');
  WHEN VALUE_ERROR THEN
    ROLLBACK;
    RAISE_APPLICATION_ERROR(-20015, 'VALOR INVÁLIDO EN PRODUCTO');
  WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
END;
/

/* ================================================================
   R7 - PROCEDIMIENTO DE INSERCIÓN PARA CLIENTES
   ================================================================ */
CREATE OR REPLACE PROCEDURE CACB_CARGA_CLIENTE(
  COD_CLIENTE_P       IN CACB_CLIENTE.COD_CLIENTE%TYPE DEFAULT NULL,
  NOMBRE_CLIENTE_P    IN CACB_CLIENTE.NOMBRE_CLIENTE%TYPE,
  APELLIDO1_CLIENTE_P IN CACB_CLIENTE.APELLIDO1_CLIENTE%TYPE,
  APELLIDO2_CLIENTE_P IN CACB_CLIENTE.APELLIDO2_CLIENTE%TYPE DEFAULT NULL,
  EMAIL_CLIENTE_P     IN CACB_CLIENTE.EMAIL_CLIENTE%TYPE DEFAULT NULL
) IS
  EMAIL_FINAL CACB_CLIENTE.EMAIL_CLIENTE%TYPE;
BEGIN
  LOCK TABLE CACB_CLIENTE IN ROW EXCLUSIVE MODE;

  IF EMAIL_CLIENTE_P IS NULL THEN
    EMAIL_FINAL := CACB_GENERA_EMAIL(NOMBRE_CLIENTE_P, APELLIDO1_CLIENTE_P);
  ELSE
    EMAIL_FINAL := EMAIL_CLIENTE_P;
  END IF;

  INSERT INTO CACB_CLIENTE(
    COD_CLIENTE, NOMBRE_CLIENTE, APELLIDO1_CLIENTE,
    APELLIDO2_CLIENTE, EMAIL_CLIENTE)
  VALUES (
    COD_CLIENTE_P, NOMBRE_CLIENTE_P, APELLIDO1_CLIENTE_P,
    APELLIDO2_CLIENTE_P, EMAIL_FINAL);

  COMMIT;
EXCEPTION
  WHEN DUP_VAL_ON_INDEX THEN
    ROLLBACK;
    RAISE_APPLICATION_ERROR(-20021, 'CLIENTE O CORREO DUPLICADO');
  WHEN VALUE_ERROR THEN
    ROLLBACK;
    RAISE_APPLICATION_ERROR(-20022, 'VALOR INVÁLIDO EN CLIENTE');
  WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
END;
/

