  START WITH 1 INCREMENT BY 1 MINVALUE 1 NOCYCLE NOCACHE;

CREATE OR REPLACE TRIGGER CACB_CLIENTE_AUTOINCREMENTAL
BEFORE INSERT ON CACB_CLIENTE
FOR EACH ROW
WHEN (NEW.COD_CLIENTE IS NULL)
BEGIN
  :NEW.COD_CLIENTE := CACB_SEQ_CLIENTE.NEXTVAL;
END;
