create or replace TRIGGER TRG_GIGH_USUARIO_PK
BEFORE INSERT
ON GIGH_USUARIO
FOR EACH ROW
DECLARE 
    TEMP NUMBER;
BEGIN
	SELECT MAX(COD_USUARIO)+1 INTO TEMP
	FROM GIGH_USUARIO;
	IF TEMP IS NULL THEN
		TEMP := 1;
	END IF;
    :NEW.COD_USUARIO := TEMP;
END;
/



