-- LUEGO CREARÁ UNA FUNCIÓN QUE SE ENCARGUE DE GENERAR LOS CORREOS
-- ELECTRÓNICOS DE LA SIGUIENTE FORMA: PRIMERA Y SEGUNDA LETRA DEL
-- NOMBRE, TERCERA Y CUARTA LETRA DEL PRIMER APELLIDO, SEGUIDO DE UN
-- PUNTO Y EL SEGUNDO APELLIDO COMPLETO QUE TERMINE EN @TESTSQL.CL

CREATE OR REPLACE FUNCTION GIGH_GENERA_CORREO(
    NOMBRE_USUARIO_P    VARCHAR2,
    APELLIDO1_USUARIO_P VARCHAR2,
    APELLIDO2_USUARIO_P VARCHAR2
)
RETURN VARCHAR2
IS
BEGIN
    RETURN UPPER(SUBSTR(NOMBRE_USUARIO_P, 1, 2) || SUBSTR(APELLIDO1_USUARIO_P, 3, 2) || '.' || APELLIDO2_USUARIO_P || '@TESTSQL.CL');
END;

-- MODIFICAR SU PROCEDIMIENTO ALMACENADO DE CARGA DE DATOS,
-- INCORPORANDO DENTRO DE LA CARGA DE DATOS EL CORREO
-- LUEGO REALIZAR UN DELETE FROM A LA TABLA SIN
-- RESTRICCIONES LIMPIARLA Y LUEGO UN LLAMADO AL PROCEDIMIENTO
-- ALMACENADO PARA LA CARGA DE UN REGISTRO DONDE SE UTILICE LA
-- FUNCIÓN.

CREATE OR REPLACE PROCEDURE GIGH_CARGA_USUARIOS(
	NOMBRE_USUARIO_P VARCHAR2,
	APELLIDO1_USUARIO_P VARCHAR2,
	APELLIDO2_USUARIO_P VARCHAR2
)
IS
BEGIN
	LOCK TABLE GIGH_USUARIO IN ROW EXCLUSIVE MODE;
	INSERT INTO GIGH_USUARIO(COD_USUARIO, NOMBRE_USUARIO, APELLIDO1_USUARIO, APELLIDO2_USUARIO,EMAIL)
	VALUES(GIGH_PK_USUARIO.NEXTVAL, NOMBRE_USUARIO_P, APELLIDO1_USUARIO_P, APELLIDO2_USUARIO_P,GIGH_GENERA_CORREO(NOMBRE_USUARIO_P,APELLIDO1_USUARIO_P,APELLIDO2_USUARIO_P));
	COMMIT;
	EXCEPTION
		WHEN PROGRAM_ERROR THEN
			RAISE_APPLICATION_ERROR(-6501,'ERROR INTERNO DEL PROGRAMA');
		WHEN OTHERS THEN
			RAISE_APPLICATION_ERROR(-20010,'UPSI FALLÉ =(');
		ROLLBACK;
END;



