-- -------------------------------------------------------------
-- 1) TABLA GIGH_DETALLE_NOTAS + PK + secuencia + triggers
-- -------------------------------------------------------------
CREATE TABLE GIGH_DETALLE_NOTAS(
  NRO_DETALLE NUMBER CONSTRAINT PK_GIGH_DETALLE_NOTAS PRIMARY KEY,
  NOTA1       NUMBER,
  NOTA2       NUMBER,
  NOTA3       NUMBER,
  PROMEDIO    NUMBER
);

CREATE SEQUENCE SEQ_GIGH_DETALLE_NOTAS START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER TRG_GIGH_DETALLE_NOTAS_PK
BEFORE INSERT ON GIGH_DETALLE_NOTAS
FOR EACH ROW
WHEN (NEW.NRO_DETALLE IS NULL)
BEGIN
  :NEW.NRO_DETALLE := SEQ_GIGH_DETALLE_NOTAS.NEXTVAL;
END;
/
CREATE OR REPLACE TRIGGER TRG_GIGH_PROMEDIO_AUTO
BEFORE INSERT OR UPDATE OF NOTA1, NOTA2, NOTA3 ON GIGH_DETALLE_NOTAS
FOR EACH ROW
BEGIN
  :NEW.PROMEDIO := ROUND((NVL(:NEW.NOTA1,0)+NVL(:NEW.NOTA2,0)+NVL(:NEW.NOTA3,0))/3,1);
END;
/
