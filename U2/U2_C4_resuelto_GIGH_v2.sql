-- -------------------------------------------------------------
-- 2) TABLA GIGH_USUARIO (estructura según U2_C1) + correo único
-- -------------------------------------------------------------
CREATE TABLE GIGH_USUARIO(
  COD_USUARIO        NUMBER CONSTRAINT PK_GIGH_USUARIO PRIMARY KEY,
  NOMBRE_USUARIO     VARCHAR2(25),
  APELLIDO1_USUARIO  VARCHAR2(25),
  APELLIDO2_USUARIO  VARCHAR2(25),
  CORREO             VARCHAR2(200) NOT NULL
);

ALTER TABLE GIGH_USUARIO ADD CONSTRAINT UQ_GIGH_USUARIO_CORREO UNIQUE (CORREO);

CREATE SEQUENCE SEQ_GIGH_USUARIO START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER TRG_GIGH_USUARIO_PK
BEFORE INSERT ON GIGH_USUARIO
FOR EACH ROW
WHEN (NEW.COD_USUARIO IS NULL)
BEGIN
  :NEW.COD_USUARIO := SEQ_GIGH_USUARIO.NEXTVAL;
END;
/
-- Mayúsculas en campos de texto (coincide con práctica pedida en U2_C4)
CREATE OR REPLACE TRIGGER TRG_GIGH_USUARIO_UPPER
BEFORE INSERT OR UPDATE ON GIGH_USUARIO
FOR EACH ROW
BEGIN
  :NEW.NOMBRE_USUARIO    := UPPER(NVL(:NEW.NOMBRE_USUARIO,   ''));
  :NEW.APELLIDO1_USUARIO := UPPER(NVL(:NEW.APELLIDO1_USUARIO,''));
  :NEW.APELLIDO2_USUARIO := UPPER(NVL(:NEW.APELLIDO2_USUARIO,''));
  :NEW.CORREO            := UPPER(NVL(:NEW.CORREO,           ''));
END;
/
-- -------------------------------------------------------------
-- 3) PA sin PK en parámetros, usando %TYPE y correo único
--    Formato base: AAAA.APELLIDO2@TESTSQL.CL (AAAA = 4 primeras de APELLIDO1)
--    Si existe, agrega sufijo 1,2,3... antes de la @
-- -------------------------------------------------------------
CREATE OR REPLACE PROCEDURE GIGH_CARGA_USUARIOS(
  NOMBRE_USUARIO_P     IN GIGH_USUARIO.NOMBRE_USUARIO%TYPE,
  APELLIDO1_USUARIO_P  IN GIGH_USUARIO.APELLIDO1_USUARIO%TYPE,
  APELLIDO2_USUARIO_P  IN GIGH_USUARIO.APELLIDO2_USUARIO%TYPE
) AS
  v_nom   GIGH_USUARIO.NOMBRE_USUARIO%TYPE    := TRIM(NOMBRE_USUARIO_P);
  v_ap1   GIGH_USUARIO.APELLIDO1_USUARIO%TYPE := TRIM(APELLIDO1_USUARIO_P);
  v_ap2   GIGH_USUARIO.APELLIDO2_USUARIO%TYPE := TRIM(APELLIDO2_USUARIO_P);
  v_base  VARCHAR2(200);
  v_mail  VARCHAR2(200);
  v_idx   NUMBER := 0;
  v_cnt   NUMBER;
BEGIN
  v_base := SUBSTR(UPPER(v_ap1),1,4) || '.' || UPPER(v_ap2) || '@TESTSQL.CL';
  v_mail := v_base;

  LOOP
    SELECT COUNT(*) INTO v_cnt FROM GIGH_USUARIO WHERE CORREO = v_mail;
    EXIT WHEN v_cnt = 0;
    v_idx  := v_idx + 1;
    v_mail := REGEXP_REPLACE(v_base, '(@TESTSQL\.CL)$', TO_CHAR(v_idx) || '\1');
  END LOOP;

  INSERT INTO GIGH_USUARIO (NOMBRE_USUARIO, APELLIDO1_USUARIO, APELLIDO2_USUARIO, CORREO)
  VALUES (v_nom, v_ap1, v_ap2, v_mail);
END;
/
